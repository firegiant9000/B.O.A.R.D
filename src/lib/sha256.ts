/**
 * Synchronous, dependency-free SHA-256 (FIPS 180-4), hand-rolled because no
 * platform this app ships on offers a synchronous digest: Node's `crypto`
 * (used by functions/src/ai/usage.ts's `hashWorkspaceId`, the precedent this
 * mirrors) doesn't exist in a React Native bundle, and both the Web Crypto
 * API (`crypto.subtle.digest`) and `expo-crypto`'s `digestStringAsync` are
 * async-only on every platform — unusable from a call site
 * (analyticsService.ts) that must stay synchronous so a caller can `track()`
 * and immediately trust the event shipped. `expo-crypto`'s synchronous
 * `getRandomBytes` (see secureRandom.ts) has no digest equivalent.
 *
 * Verified byte-for-byte against Node's `crypto.createHash("sha256")` across
 * empty input, ASCII, multi-byte UTF-8, and inputs straddling the 55/56/63/64
 * byte block-padding boundaries (see the test file) — this is not an
 * approximation of SHA-256, it is SHA-256.
 */

